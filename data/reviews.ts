export function getFeaturedReviews(limit = 6): Review[] {
  return reviews
    .filter((r) => r.verifiedPurchase && r.rating >= 4)
    .sort((a, b) => (b.helpfulCount ?? 0) - (a.helpfulCount ?? 0))
    .slice(0, limit)
}
